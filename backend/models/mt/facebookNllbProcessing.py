import os
import logging

logger = logging.getLogger(__name__)


def load_transcript_file(file_location: str):
    """
    Read a transcript file from disk and return its contents as a string.

    Parameters
    ----------
    file_location : str
        Path to the file.

    Returns
    -------
    str
        The transcript as a single string.
    """

    try:

        if not os.path.exists(file_location):
            raise FileNotFoundError(f"Transcript not found at {file_location}")

        with open(file_location, "r", encoding="utf-8") as f:
            content = f.read()

        return content

    except Exception as e:
        logger.error(e)
        return None


def save_translation(
    translation: str = None, file_name: str = "translation.txt", save_dir: str = None
):
    """
    Save the machine translation output to a text file.

    Parameters
    ----------
    translation : str
        Translation generated by the MT model.

    file_name : str, default="translation.txt"
        Name of the output file.

    save_dir : str, default=None
        Path to the directory where the file should be saved.

    Returns
    -------
    str
        Path to the saved translation file.
    """

    try:

        if not save_dir or not os.path.exists(save_dir):
            raise FileNotFoundError(f"Directory not found: {save_dir}")

        file_path = os.path.join(save_dir, file_name)

        with open(file_path, "w", encoding="utf-8") as f:
            f.write(translation)

        return file_path

    except Exception as e:
        logger.error(e)
        return None
